import 'package:flutter/material.dart';

/// Lightweight, hand-rolled localization (English + Hindi).
///
/// We keep a plain key→string map per language instead of generated ARB code:
/// it is fully deterministic, has zero build-time codegen, and is trivial to
/// extend. Number / currency / date formatting is handled by [Intl] elsewhere.
class AppStrings {
  AppStrings(this.locale);

  final Locale locale;

  static const List<Locale> supported = <Locale>[Locale('en'), Locale('hi'), Locale('kn')];

  static AppStrings of(BuildContext context) =>
      Localizations.of<AppStrings>(context, AppStrings) ?? AppStrings(const Locale('en'));

  static const LocalizationsDelegate<AppStrings> delegate = _AppStringsDelegate();

  String t(String key) {
    final Map<String, String> table = _values[locale.languageCode] ?? _values['en']!;
    return table[key] ?? _values['en']![key] ?? key;
  }

  /// Interpolate `{}` placeholders positionally.
  String f(String key, List<Object> args) {
    String out = t(key);
    for (final Object a in args) {
      out = out.replaceFirst('{}', '$a');
    }
    return out;
  }

  static const Map<String, Map<String, String>> _values = <String, Map<String, String>>{
    'en': _en,
    'hi': _hi,
    'kn': _kn,
  };
}

class _AppStringsDelegate extends LocalizationsDelegate<AppStrings> {
  const _AppStringsDelegate();

  @override
  bool isSupported(Locale locale) =>
      AppStrings.supported.any((Locale l) => l.languageCode == locale.languageCode);

  @override
  Future<AppStrings> load(Locale locale) async => AppStrings(locale);

  @override
  bool shouldReload(_AppStringsDelegate old) => false;
}

